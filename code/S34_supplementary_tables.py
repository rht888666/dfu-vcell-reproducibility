# -*- coding: utf-8 -*-
"""
S34 - Generate Supplementary Tables S1-S4 from machine artefacts.
所有数值实时从 JSON 读取，不硬编码。

输出: SUPPLEMENTARY_TABLES.md
"""
import json, os

BASE = os.path.dirname(os.path.abspath(__file__))


def J(n):
    with open(os.path.join(BASE, n), encoding='utf-8') as f:
        return json.load(f)


L = []
L.append('# Supplementary Tables')
L.append('All values generated by `S34_supplementary_tables.py` from locked JSON artefacts. '
         'No value is transcribed by hand; the manuscript text is audited against these same artefacts by `S32b_manuscript_audit.py`.')
L.append('')

# ---------------- S1: provenance
P = J('S31_provenance.json')
L.append('## Table S1. GSE241124 sample provenance audit (reverse-coverage criterion)')
L.append('')
L.append(f'- h5 files in tar: **{P["tar_h5_count"]}**; extracted locally: **{P["local_h5_count"]}**')
L.append(f'- Independently usable donors recovered: **{P["true_independent_donors"]}**')
L.append(f'- Mapping conflicts: **{len(P.get("conflicts", []))}**')
L.append('')
L.append('| Metadata sample | Mapped h5 stem | Reverse coverage |')
L.append('|---|---|---|')
mp = P.get('mapping', {})
if isinstance(mp, dict):
    for k in sorted(mp.keys()):
        v = mp[k]
        if isinstance(v, dict):
            L.append(f'| {k} | {v.get("h5_stem", v.get("stem", "?"))} | {v.get("rev_cov", v.get("coverage", "?"))} |')
        else:
            L.append(f'| {k} | {v} | — |')
else:
    for row in mp:
        L.append('| ' + ' | '.join(str(x) for x in row) + ' |')
L.append('')
L.append('**Criterion.** Each metadata sample\'s barcode set must be fully contained in **exactly one** matrix file. '
         'Barcode-intersection and (barcode, count) fingerprinting were both tested and rejected: Visium barcodes are '
         'reused across slides (a 55 µm grid is shared), and the filtered matrix counts use a different denominator '
         'from the metadata counts. The reverse-coverage test yields a 16/16 one-to-one mapping.')
L.append('')

# ---------------- S2: spatial gradient by timepoint
S = J('S29b_gradient_specificity.json')
pg = S['program_gradients']
L.append('## Table S2. Wound-edge distance gradient by programme and timepoint (GSE241124)')
L.append('')
L.append('This table is the expanded form of main-text Table 3, which reports the D7 column. '
         'It documents the choice of D7 explicitly.')
L.append('')
tps = ['Skin', 'Wound1', 'Wound7', 'Wound30']
progs = ['F6', 'F7', 'F7e', 'F1', 'F5']
L.append('| Programme | ' + ' | '.join(tps) + ' |')
L.append('|---|' + '---|' * len(tps))
for p in progs:
    cells = []
    for t in tps:
        k = f'{t}_{p}'
        if k in pg:
            r, pp = pg[k]['rho'], pg[k]['p_emp']
            star = '*' if pp < 0.001 else ('†' if pp < 0.05 else '')
            cells.append(f'{r:+.3f} (p={pp:.4f}){star}')
        else:
            cells.append('—')
    L.append(f'| **{p}** | ' + ' | '.join(cells) + ' |')
L.append('')
L.append('*p* = empirical p from random-gene null (2,000 draws of 5–7 markers). '
         '†*p* < 0.05; \\**p* < 0.001. Negative values = enrichment toward the wound edge.')
L.append('')

# ---------------- S3: double difference
dd = S['double_diff']
L.append('## Table S3. Double-difference contrasts vs negative controls (GSE241124)')
L.append('')
contrasts = list(dd.keys())
L.append('| Contrast | ' + ' | '.join(tps) + ' |')
L.append('|---|' + '---|' * len(tps))
for c in contrasts:
    cells = []
    for t in tps:
        d = dd[c].get(t)
        if d:
            star = '\\*' if d['p'] < 0.01 else ('†' if d['p'] < 0.05 else '')
            cells.append(f"{d['rho']:+.3f} (p={d['p']:.4f}){star}")
        else:
            cells.append('—')
    L.append(f'| {c} | ' + ' | '.join(cells) + ' |')
L.append('')
L.append('Double-difference = programme score minus negative-control score; this removes any global tissue gradient '
         'shared by both. Null sd is computed from the same random-gene draws applied to the difference.')
L.append('')

# ---------------- S4: depth schemes
W = J('S25b_scheme_comparison.json')['results']
L.append('## Table S4. Depth-handling scheme matrix (GSE165816, Healer vs NonHealer)')
L.append('')
L.append('| Scheme | n (H/NH) | Observed Δ | p | Residual ρ vs depth | Verdict |')
L.append('|---|---|---|---|---|---|')
labels = {'raw': 'Raw score', 'd_matched': 'Depth-matched pairs', 'e_ratio_F7F6': 'Ratio F7/F6',
          'a_lin_resid': 'Linear residualization', 'b_rank_resid': '**Rank residualization**',
          'c_stratum_z': 'Stratified z (depth tercile)'}
verdicts = {'raw': 'confounded', 'd_matched': 'n=5 only', 'e_ratio_F7F6': 'still confounded',
            'a_lin_resid': 'over-corrects', 'b_rank_resid': '**only clean scheme**', 'c_stratum_z': 'clean'}
order = ['raw', 'd_matched', 'e_ratio_F7F6', 'a_lin_resid', 'b_rank_resid', 'c_stratum_z']
for k in order:
    d = W[k]
    nh = d.get('n_h', d.get('n_healer', 9))
    nn = d.get('n_nh', d.get('n_nonhealer', 5))
    ur = d.get('umi_rho', float('nan'))
    ur_s = f'{ur:+.3f}' if ur == ur else '—'
    L.append(f"| {labels[k]} | {int(nh)}/{int(nn)} | {d['obs']:+.3f} | {d['p']:.3f} | {ur_s} | {verdicts[k]} |")
L.append('')
L.append('Linear residualization is reported only to document its over-correction behaviour: applied to an '
         'unrelated programme (F5, ρ = +0.03 with depth), it manufactures a correlation of −0.75. '
         'Rank residualization is the only scheme that removes the confound (residual ρ = 0.000) while preserving rank structure.')
L.append('')

# ---------------- S5: Markov transitions
M = J('S24_markov_state_model.json')
L.append('## Table S5. Markov quadrant transitions per donor (GSE241132)')
L.append('')
L.append('| Donor | D0 | D1 | D7 | D30 |')
L.append('|---|---|---|---|---|')
ds = M['donor_states']
for don in ['PWH26', 'PWH27', 'PWH28']:
    st = ds.get(don, [])
    short = [x.split('(')[0] for x in st]
    L.append(f'| {don} | ' + ' | '.join(short) + ' |')
L.append('')
L.append('Quadrants: R = F6⁻F7⁻, I = F6⁺F7⁻, M = F6⁻F7⁺, T = F6⁺F7⁺. '
         'All 3/3 donors traverse I→M; one donor transiently visits R.')
L.append('')
L.append('### Transition count matrix (all donors pooled)')
L.append('')
tc = M['trans_counts']
L.append('| from \\ to | R | I | M | T |')
L.append('|---|---|---|---|---|')
for i, row in enumerate(tc):
    L.append('| ' + ['R', 'I', 'M', 'T'][i] + ' | ' + ' | '.join(str(int(x)) for x in row) + ' |')
L.append('')

# ---------------- S6: fibroblast subtype x programme matrix (S35)
R = J('S35_selfaudit_redundancy.json')
at = R['annotation_table']
L.append('## Table S6. Spatial programme score by cell-type category (GSE241124, all sections pooled)')
L.append('')
L.append('Full subtype × programme matrix underlying the main-text claim that **F7e**, not F7, is FB1-specific. '
         'Values are mean depth-residualized programme scores per Visium spot, aggregated by the 17 `AnnoType` '
         'categories. No value is transcribed by hand (`S35_selfaudit_redundancy.py`).')
L.append('')
L.append('| Category | *n* spots | F6 | F7 | F7e | F1 (neg) | F5 (neg) |')
L.append('|---|---|---|---|---|---|---|')
for row in sorted(at, key=lambda r: -r['n']):
    L.append(f"| {row['AnnoType']} | {row['n']:,} | {row['F6']:+.3f} | {row['F7']:+.3f} | "
             f"{row['F7e']:+.3f} | {row['F1']:+.3f} | {row['F5']:+.3f} |")
L.append('')
L.append('### FB1 preference: subtype-level test')
L.append('')
q1 = R['q1_fb1_vs_otherFIB']
pm = R['perm_q1']
L.append('| Programme | FB1 mean | Mean of other fibroblast subtypes | Δ | category-level *p* | Verdict |')
L.append('|---|---|---|---|---|---|')
for p in ['F6', 'F7', 'F7e', 'F1', 'F5']:
    d = q1[p]
    pv = pm.get(p, {}).get('p')
    pv_s = f'{pv:.4f}' if pv is not None else '—'
    if p in ('F1', 'F5'):
        verdict = 'negative control ✅'
    elif pv is not None and pv < 0.05:
        verdict = '**FB1-specific**'
    else:
        verdict = 'not subtype-specific'
    L.append(f"| {p} | {d['fb1']:+.3f} | {d['other_fib_mean']:+.3f} | **{d['delta']:+.3f}** | {pv_s} | {verdict} |")
L.append('')
L.append('Other fibroblast subtypes = FB2, Sweatgland_FB, Dermis1, Dermis2, Papillary_dermis. '
         'Category-level permutation shuffles programme labels across the 17 categories (5,000×), i.e. it asks whether '
         'FB1 is enriched for a programme *relative to other fibroblast subtypes*, not merely relative to all spots. '
         'F7 fails this stricter test (*p* = 0.409) whereas F7e passes it (*p* = 0.0002); the FB1 F7 elevation is '
         'consistent with smooth-muscle admixture at 55 µm resolution (`Smooth_muscle` F7 = +0.510).')
L.append('')

with open(os.path.join(BASE, 'SUPPLEMENTARY_TABLES.md'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(L))
print('\n'.join(L))
print('\n[saved] SUPPLEMENTARY_TABLES.md')
